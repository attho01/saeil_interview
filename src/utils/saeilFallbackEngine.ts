export function extractTextFromCandidateInput(files: any[], resumeText?: string, storyBankText?: string): string {
  let combined = '';
  if (Array.isArray(files)) {
    for (const f of files) {
      if (f.extractedText) {
        combined += `\n[파일: ${f.name}]\n${f.extractedText}\n`;
      } else if (f.name) {
        combined += `\n[첨부 파일명: ${f.name}]\n`;
      }
    }
  }
  if (resumeText) combined += `\n[이력서 내용]\n${resumeText}\n`;
  if (storyBankText) combined += `\n[스토리뱅크 내용]\n${storyBankText}\n`;
  return combined.trim();
}

